#!/usr/bin/env node
/**
 * Copies the pure rules/evidence modules from the Next app into the mobile
 * app, so both run the SAME publication gate and the same fee verdicts.
 *
 *   web/src/lib/rules.json          -> mobile/src/shared/rules.json
 *   web/src/lib/listing-rules.ts    -> mobile/src/shared/listing-rules.ts
 *   web/src/lib/listing-evidence.ts -> mobile/src/shared/listing-evidence.ts
 *
 * Runs automatically before `npm start` in mobile/. Edit the web copies only;
 * the mobile copies are overwritten on every run.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const from = join(root, "web", "src", "lib");
const to = join(root, "mobile", "src", "shared");
mkdirSync(to, { recursive: true });

const banner = (name) =>
  `/* GENERATED by tools/sync-mobile-shared.mjs from web/src/lib/${name}. Do not edit here. */\n`;

for (const name of ["listing-rules.ts", "listing-evidence.ts"]) {
  const src = readFileSync(join(from, name), "utf8");
  writeFileSync(join(to, name), banner(name) + src);
}
writeFileSync(join(to, "rules.json"), readFileSync(join(from, "rules.json"), "utf8"));
console.log("[sync-mobile-shared] rules.json, listing-rules.ts, listing-evidence.ts -> mobile/src/shared");
